    }

    /** Defaults merged with whatever admin has saved in the DB. */
    public static function all(): array
    {
        $defaults = self::defaults();
        $saved = ThemeSetting::all()->groupBy('mode');

        foreach (['dark', 'light'] as $mode) {
            foreach ($saved->get($mode, []) as $row) {
                if (array_key_exists($row->variable, $defaults[$mode])) {
                    $defaults[$mode][$row->variable] = $row->value;
                }
            }
        }

        return $defaults;
    }

    public static function generateCss(): string
    {
        $all = self::all();

        $css = "/* auto-generated by ThemeService — do not edit by hand */\n";
        $css .= ":root {\n";
        foreach ($all['dark'] as $var => $val) {
            $css .= "  --{$var}: {$val};\n";
        }
        $css .= "}\n\n.light-mode {\n";
        foreach ($all['light'] as $var => $val) {
            $css .= "  --{$var}: {$val};\n";
        }
        $css .= "}\n";

        return $css;
    }

    public static function cachedCss(): string
    {
        return Cache::rememberForever(self::CACHE_KEY, fn() => self::generateCss());
    }

    public static function clearCache(): void
    {
        Cache::forget(self::CACHE_KEY);
    }

    /** Cache-busting query string for the <link> tag in the layout. */
    public static function version(): string
    {
        $latest = ThemeSetting::max('updated_at');
        return $latest ? md5((string) $latest) : 'default';
    }
}
