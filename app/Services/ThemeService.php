namespace App\Services;

use App\Models\ThemeSetting;
use Illuminate\Support\Facades\Cache;

class ThemeService
{
    const CACHE_KEY = 'theme.dynamic.css';

    /**
     * Defaults mirror the :root / .light-mode values already shipped
     * in common.css. Only variables listed here are editable from the
     * admin panel — add more keys here (and re-seed) to expose them.
     */
    public static function defaults(): array
    {
        return [
            'dark' => [
                'primary-color'    => '#0d56de',
                'bg-main'          => '#0a0f1d',
                'black-color'      => '#0f1522',
